String interpretationInstructionForAttempt(int attempt) => attempt == 0
    ? interpretationInstruction
    : '$interpretationInstruction\nCall exactly one provided function with valid parameters. kind/topic IDs are not function names. Use only the supplied situation IDs or the current question choice ID.';

/// Reduce duplicated UI metadata without truncating the citizen's words.
Map<String, Object?> buildModelRequest(
  Map<String, dynamic> request, {
  bool minimal = false,
}) {
  final context = Map<String, dynamic>.from(request['context'] as Map);
  final question = context['question'];
  final options = question is Map ? question['options'] as List? ?? [] : [];
  context['choices'] = (context['choices'] as List)
      .whereType<Map>()
      .where(
        (choice) => options.any(
          (option) => option is Map && option['id'] == choice['id'],
        ),
      )
      .map((choice) => {'id': choice['id'], 'label': choice['label']})
      .toList();
  // The app owns confirmed answers, filtering and navigation. The extractor
  // needs current words/question, not duplicate policy facets or old facts.
  context.remove('situationIndex');
  context.remove('knownAnswers');
  context.remove('currentNeed');
  context.remove('allowedFacts');
  if (context['question'] is Map) {
    final question = Map<String, dynamic>.from(context['question'] as Map)
      ..remove('options');
    context['question'] = question;
  }
  if (minimal) {
    context['situations'] = (context['situations'] as List)
        .whereType<Map>()
        .map((s) => {'id': s['id'], 'label': s['label']})
        .toList();
  }
  return {'input': request['input'], 'context': context};
}

/// Native tools constrain the small model to choosing directions/actions. It
/// never generates personal values or evidence; those candidates come from input.
List<Map<String, dynamic>> interpretationTools(Map<String, dynamic> request) {
  final context = request['context'] as Map;
  Map<String, dynamic> tool(
    String name,
    String description,
    Map<String, dynamic> properties,
  ) => {
    'name': name,
    'description': description,
    'parameters': {
      'type': 'object',
      'properties': properties,
      'required': properties.keys.toList(),
      'additionalProperties': false,
    },
  };
  final tools = [
    tool(
      'record_situation',
      'Record actual needs; background only uses an empty situationIds array.',
      {
        'situationIds': {
          'type': 'array',
          'maxItems': 3,
          'uniqueItems': true,
          'items': {
            'type': 'string',
            'enum': (context['situations'] as List)
                .whereType<Map>()
                .map((s) => s['id'])
                .toList(),
          },
        },
      },
    ),
    tool('clarify', 'Ask for a direction or clarify an ambiguous request.', {}),
    tool(
      'off_topic',
      'The input is unrelated to welfare or life resources.',
      {},
    ),
  ];
  final q = context['question'];
  if (q is Map && q['kind'] == 'number') {
    tools.add(
      tool(
        'answer_number',
        'Propose an answer to the current single number question only.',
        {
          'numberValue': {
            'type': 'integer',
            'minimum': q['min'] ?? 0,
            'maximum': q['max'] ?? 130,
          },
        },
      ),
    );
  } else if (q is Map) {
    final choices = (context['choices'] as List)
        .whereType<Map>()
        .where(
          (c) => (q['options'] as List? ?? []).whereType<Map>().any(
            (o) => o['id'] == c['id'],
          ),
        )
        .map((c) => c['id'])
        .toList();
    if (choices.isNotEmpty) {
      tools.add(
        tool('answer_choice', 'Propose one current question answer only.', {
          'choiceId': {'type': 'string', 'enum': choices},
        }),
      );
    }
  }
  return tools;
}

List<Map<String, Object?>> _requestFacts(Map<String, dynamic> request) {
  final allowed = ((request['context'] as Map)['allowedFacts'] as List)
      .whereType<Map>()
      .map((f) => f['field'])
      .toSet();
  final input = request['input'] as String;
  var extracted = extractFactCandidates(input);
  // A visible confirmation question may identify which one of the original
  // people is being corrected. It supplies no new value or evidence: both old
  // identity and new age still have to occur in the citizen's original input.
  const marker = '\n這次補充或修正：';
  final split = input.indexOf(marker);
  final prompt = (request['context'] as Map)['followupQuestion'];
  if (extracted.isEmpty &&
      input.startsWith('先前說法：') &&
      split > 0 &&
      prompt is String) {
    final previous = input.substring('先前說法：'.length, split);
    final current = input.substring(split + marker.length);
    final visible = extractFactCandidates(previous)
        .where(
          (f) =>
              f['field'] == 'age' && prompt.contains(f['evidence'] as String),
        )
        .toList();
    if (visible.length == 1) {
      extracted = extractFactCandidates(
        '先前說法：${visible.single['evidence']}\n這次補充或修正：$current',
      );
    }
  }
  return extracted.where((f) => allowed.contains(f['field'])).toList();
}

Map<String, Object?>? directBackgroundInterpretation(
  Map<String, dynamic> request,
) {
  final input = request['input'] as String;
  if ((request['context'] as Map)['question'] is Map) return null;
  final facts = _requestFacts(request);
  final describesNeed = RegExp(r'想|需要|急需|幫忙|補助|補貼|津貼|資源|付不起|繳不|壓力|負擔|照顧|房租|學費')
      .hasMatch(input);
  if (facts.isEmpty &&
      !describesNeed &&
      RegExp(r'歲|戶籍|設籍|戶口|在學|學生|低收入戶|一般戶').hasMatch(input) &&
      RegExp(r'不確定|不知道|不清楚|可能|也許|好像|大概|左右|不是|未核定').hasMatch(input)) {
    return parseInterpretation('{"kind":"clarify"}', request);
  }
  if (facts.isEmpty || describesNeed || RegExp(r'嗎|[?？]').hasMatch(input)) {
    return null;
  }
  final clauses = input
      .split(RegExp(r'[，,。；;、！!\n]'))
      .where((s) => s.trim().isNotEmpty);
  const cities =
      '臺北|台北|新北|桃園|臺中|台中|臺南|台南|高雄|基隆|新竹|苗栗|彰化|南投|雲林|嘉義|屏東|宜蘭|花蓮|臺東|台東|澎湖|金門|連江';
  final locationBackground = RegExp(
    '^(?:我|本人)(?:目前|現在)?(?:住(?:在)?|居住(?:在)?|在)(?:$cities)(?:市|縣)?(?:工作|上班|租屋)?\$',
  );
  final explicitAgeCorrection =
      facts.every((f) => f['field'] == 'age') &&
      RegExp(r'更正|改成|改為|正確是|這次補充或修正').hasMatch(input);
  if (!explicitAgeCorrection &&
      !clauses.every(
        (clause) =>
            extractFactCandidates(clause.trim()).isNotEmpty ||
            locationBackground.hasMatch(clause.trim()),
      )) {
    return null;
  }
  return parseInterpretation(
    jsonEncode({
      'kind': 'situation',
      'situationIds': [],
      'facts': facts,
      'details': [],
      'uncertainties': [],
    }),
    request,
  );
}

Map<String, Object?> parseToolInterpretation(
  String name,
  Map<String, dynamic> args,
  Map<String, dynamic> request,
) {
  final definitions = interpretationTools(request)
      .where((t) => t['name'] == name);
  if (definitions.isEmpty) {
    throw const FormatException('unknown_interpretation_tool');
  }
  final properties =
      (definitions.first['parameters'] as Map)['properties'] as Map;
  if (args.length != properties.length ||
      args.keys.any((k) => !properties.containsKey(k))) {
    throw const FormatException('invalid_tool_parameters');
  }
  final input = request['input'] as String;
  final facts = _requestFacts(request);
  final details = input
      .split(RegExp(r'[，,。；;\n]'))
      .where((s) => s.trim().isNotEmpty)
      .expand((s) sync* {
        for (var i = 0; i < s.length; i += 200) {
          yield s.substring(i, i + 200 > s.length ? s.length : i + 200);
        }
      })
      .take(6)
      .toList();
  final Map<String, Object?> canonical;
  switch (name) {
    case 'record_situation':
      canonical = {
        'kind': 'situation',
        'situationIds': explicitRequestedDirections(
          input,
          args['situationIds'],
          ((request['context'] as Map)['situations'] as List)
              .whereType<Map>()
              .map((s) => s['id'] as String)
              .toSet(),
        ),
        'facts': facts,
        'details': details,
        'uncertainties': [],
      };
    case 'clarify':
      canonical = facts.isEmpty
          ? {'kind': 'clarify'}
          : {
              'kind': 'situation',
              'situationIds': [],
              'facts': facts,
              'details': details,
              'uncertainties': [],
            };
    case 'off_topic':
      canonical = {'kind': 'off_topic'};
    case 'answer_choice':
      canonical = {
        'kind': 'answer',
        'choiceId': args['choiceId'],
        'evidence': input.length <= 200 ? input : input.substring(0, 200),
      };
    case 'answer_number':
      canonical = {
        'kind': 'answer',
        'numberValue': args['numberValue'],
        'evidence': input.length <= 200 ? input : input.substring(0, 200),
      };
    default:
      throw const FormatException('unknown_interpretation_tool');
  }
  return parseInterpretation(jsonEncode(canonical), request);
}

/// A literal requested service takes precedence over background associations
/// (e.g. a parent's wheelchair is an aid request, not evidence of elder care).
/// Implicit needs and clauses with additional difficulties stay with Gemma.
Object? explicitRequestedDirections(
  String input,
  Object? proposed,
  Set<String> available,
) {
  if (proposed is! List ||
      proposed.any((id) => id is! String) ||
      proposed.length > 3 ||
      proposed.toSet().length != proposed.length ||
      proposed.any((id) => !available.contains(id))) {
    return proposed;
  }
  if (RegExp(r'如果|假如|不確定|可能|或者|或是|還是|要不要|不再|不需要|不想|不用|不要|不是|沒有')
      .hasMatch(input)) {
    return proposed;
  }
  final request = RegExp(r'(?:想要|想找|想申請|想了解|需要|希望找|要找|要的是)([^，,。；;\n]{1,80})');
  final latest = input.split('\n這次補充或修正：').last;
  final text = input.contains('\n這次補充或修正：') && request.hasMatch(latest)
      ? latest
      : input;
  final matches = request.allMatches(text).toList();
  if (matches.isEmpty) return proposed;
  var remaining = text;
  final objects = <String>[];
  for (final match in matches) {
    if (match.start > 0 &&
        RegExp(r'不|沒|未|無')
            .hasMatch(text.substring(match.start - 1, match.start))) {
      return proposed;
    }
    objects.addAll(
      match
          .group(1)!
          .replaceAll(RegExp(r'[?？!！]$'), '')
          .split(RegExp(r'以及|和|與|及|、')),
    );
    remaining = remaining.replaceFirst(match.group(0)!, '');
  }
  // Do not erase an unrecognised outside clause: it may be another difficulty.
  final background = RegExp(
    r'^(?:(?:我|本人|爸爸|媽媽|父親|母親|家人))?(?:最近|目前|現在)?(?:失業(?:了|後)?|沒錢|收入變少|經濟困難)*$',
  );
  final person = RegExp(r'^(?:身障|身心障礙)的?(?:爸爸|媽媽|父親|母親|家人)$');
  if (!remaining
      .split(RegExp(r'[，,。；;\n]'))
      .every(
        (part) =>
            part.trim().isEmpty ||
            background.hasMatch(part.trim()) ||
            person.hasMatch(part.trim()) ||
            extractFactCandidates(part.trim()).isNotEmpty,
      )) {
    return proposed;
  }
  final patterns = <String, String>{
    'housing': r'(?:租屋|租金|房租)(?:補助|補貼|協助)?|住宅補助|購屋補助|修繕補助',
    'study': r'(?:學費|學雜費)(?:補助|減免)?|助學金|獎學金|就學補助',
    'living': r'生活(?:扶助|補助|費(?:救助|補助)?)|急難(?:救助|補助)?|經濟援助',
    'elder': r'長照(?:服務|補助)?|居家(?:照顧|服務)(?:服務|補助)?|敬老(?:福利|補助|津貼)?',
    'family': r'(?:育兒|托育|托嬰|生育|兒少)(?:補助|津貼|給付|服務|協助)?',
    'health': r'(?:醫療|醫藥|健保|看病|手術|住院|健康檢查)(?:補助|協助|減免|服務)?',
    'disability':
        r'(?:身障|身心障礙者?)(?:生活補助|生活津貼|補助|福利)?|(?:輪椅輔具|輪椅|助聽器|輔具)(?:補助|協助)?',
    'work': r'失業(?:給付|補助)|(?:就業|求職|職業訓練|職訓|創業)(?:津貼|補助|協助|服務|生活津貼)?',
    'community': r'(?:社區)?(?:藝文|文化)(?:活動|創作)?(?:補助|經費|支持)?|(?:社區|競賽|公益|環境|創作)(?:活動)?(?:補助|經費|支持|服務)?',
  };
  final explicit = <String>{};
  for (final object in objects) {
    final found = patterns.entries
        .where((e) => RegExp('^(?:${e.value})\$').hasMatch(object.trim()))
        .map((e) => e.key)
        .toList();
    if (found.length != 1) return proposed;
    explicit.add(found.single);
  }
  if (explicit.isEmpty ||
      explicit.length > 3 ||
      explicit.any((id) => !available.contains(id))) {
    return proposed;
  }
  return patterns.keys.where(explicit.contains).toList();
}

/// Some small bundles emit a bare parameterless control name instead of a call.
/// These exact two signals carry no values, actions, policy or mutable answers.
Map<String, Object?> parseTextControl(
  String text,
  Map<String, dynamic> request,
) {
  final match = RegExp(r'^(clarify|off_topic)(?:\{\})?$')
      .firstMatch(text.trim());
  if (match == null) {
    throw const FormatException('expected_interpretation_tool');
  }
  return parseToolInterpretation(match.group(1)!, {}, request);
}

Map<String, dynamic> validateInterpretationRequest(Object? message) {
  if (message is! Map ||
      message['requestId'] is! String ||
      (message['requestId'] as String).isEmpty ||
      (message['requestId'] as String).length > 100 ||
      message['input'] is! String ||
      (message['input'] as String).trim().isEmpty ||
      (message['input'] as String).length > 2000 ||
      message['context'] is! Map ||
      jsonEncode(message).length > 18000) {
    throw const FormatException('invalid_request');
  }
  final context = message['context'] as Map;
  if (![
    'home',
    'needs',
    'questions',
    'results',
    'search',
  ].contains(context['stage'])) {
    throw const FormatException('invalid_context');
  }
  for (final key in ['choices', 'situations', 'allowedFacts']) {
    if (context[key] is! List || (context[key] as List).length > 40) {
      throw const FormatException('invalid_context');
    }
  }
  return Map<String, dynamic>.from(message);
}

Map<String, Object?> parseInterpretation(
  String text,
  Map<String, dynamic> request,
) {
  // A single JSON code fence is presentation only. Do not fish a JSON fragment
  // out of surrounding prose, concatenate objects, or repair missing facts.
  final trimmed = text.trim();
  final fenced = RegExp(
    r'^```(?:json)?\s*\n([\s\S]*?)\n```$',
    caseSensitive: false,
  ).firstMatch(trimmed);
  final decoded = jsonDecode(fenced?.group(1) ?? trimmed);
  if (decoded is! Map<String, dynamic>) {
    throw const FormatException('invalid_json');
  }
  final result = Map<String, dynamic>.from(decoded)..remove('requestId');
  final input = request['input'] as String;
  final context = request['context'] as Map;
  Never invalid() => throw const FormatException('invalid_model_output');
  bool evidence(Object? value) =>
      value is String &&
      value.trim().isNotEmpty &&
      value.length <= 200 &&
      input.contains(value);
  void keys(Set<String> allowed) {
    if (result.keys.any((key) => !allowed.contains(key))) invalid();
  }

  bool idIn(Object? id, Object? list) =>
      id is String &&
      list is List &&
      list.any((option) => option is Map && option['id'] == id);
  switch (result['kind']) {
    case 'clarify':
    case 'off_topic':
      keys({'kind'});
    case 'answer':
      keys({'kind', 'choiceId', 'numberValue', 'evidence'});
      if (!evidence(result['evidence'])) invalid();
      final question = context['question'];
      if (question is! Map) invalid();
      final hasNumber = result.containsKey('numberValue');
      final hasChoice = result.containsKey('choiceId');
      if (hasNumber == hasChoice) invalid();
      if (hasChoice &&
          (!idIn(result['choiceId'], context['choices']) ||
              !idIn(result['choiceId'], question['options']))) {
        invalid();
      }
      if (hasNumber) {
        final number = result['numberValue'];
        if (question['kind'] != 'number' ||
            number is! int ||
            (question['min'] is num && number < question['min']) ||
            (question['max'] is num && number > question['max'])) {
          invalid();
        }
      }
    case 'situation':
      keys({'kind', 'situationIds', 'facts', 'details', 'uncertainties'});
      final ids = result['situationIds'];
      final facts = result['facts'];
      final details = result['details'];
      final uncertainties = result['uncertainties'];
      if (ids is! List ||
          ids.length > 3 ||
          ids.toSet().length != ids.length ||
          ids.any((id) => !idIn(id, context['situations'])) ||
          facts is! List ||
          facts.length > 8 ||
          details is! List ||
          details.length > 6 ||
          details.any((value) => !evidence(value)) ||
          uncertainties is! List ||
          uncertainties.length > 6 ||
          uncertainties.any(
            (value) => value is! String || value.isEmpty || value.length > 200,
          )) {
        invalid();
      }
      if (ids.isEmpty &&
          facts.isEmpty &&
          details.isEmpty &&
          uncertainties.isEmpty) {
        invalid();
      }
      for (final fact in facts) {
        if (fact is! Map ||
            fact.length != 5 ||
            !fact.keys.toSet().containsAll({
              'field',
              'value',
              'subject',
              'subjectLabel',
              'evidence',
            }) ||
            ![
              'self',
              'other',
              'applicant',
              'unclear',
            ].contains(fact['subject']) ||
            !evidence(fact['evidence'])) {
          invalid();
        }
        final label = fact['subjectLabel'];
        if (label is! String ||
            label.length > 40 ||
            (fact['subject'] != 'unclear' && label.trim().isEmpty) ||
            (label.isNotEmpty && !input.contains(label))) {
          invalid();
        }
        final field = fact['field'];
        if (![
          'age',
          'region',
          'is_student',
          'household_type',
        ].contains(field)) {
          invalid();
        }
        final allowed = (context['allowedFacts'] as List)
            .whereType<Map>()
            .where((entry) => entry['field'] == field);
        if (allowed.isEmpty) invalid();
        final spec = allowed.first;
        final value = fact['value'];
        if (spec['options'] is List &&
            !(spec['options'] as List).any(
              (option) => option is Map && option['value'] == value,
            )) {
          invalid();
        }
        if (field == 'age' &&
            (value is! int ||
                value < (spec['min'] as num? ?? 0) ||
                value > (spec['max'] as num? ?? 130))) {
          invalid();
        }
        if (field == 'region' &&
            (!['臺北市', '其他縣市'].contains(value) ||
                !regionEvidenceSupports(value, fact['evidence'] as String))) {
          invalid();
        }
        if (field == 'household_type' &&
            !['low_income', 'mid_low_income', 'general'].contains(value)) {
          invalid();
        }
        if (field == 'household_type') {
          final proof = fact['evidence'] as String;
          final deniedOrUncertain = RegExp(r'不是|沒有|未取得|未核定|不具|並非|可能|好像')
              .hasMatch(proof);
          if (value != 'general' && !proof.contains('低收入戶')) invalid();
          if (value == 'low_income' &&
              (proof.contains('中低收入戶') || deniedOrUncertain)) {
            invalid();
          }
          if (value == 'mid_low_income' &&
              (!proof.contains('中低收入戶') || deniedOrUncertain)) {
            invalid();
          }
          if (value == 'general' &&
              (proof.contains('一般戶')
                  ? deniedOrUncertain
                  : (!RegExp(r'不是|沒有|未取得|未核定|不具|並非').hasMatch(proof) ||
                        RegExp(r'中低收入戶|低收入戶').allMatches(proof).length < 2))) {
            invalid();
          }
        }
        if (field == 'is_student' && value is! bool) invalid();
      }
    default:
      invalid();
  }
  return {...result, 'requestId': request['requestId']};
}

/// Conservative evidence guard, not an address or eligibility classifier.
bool regionEvidenceSupports(Object? value, String proof) {
  if (RegExp(r'不是|不在|並非|沒有|未設籍|不確定|可能|好像').hasMatch(proof)) return false;
  const cities =
      '臺北|台北|其他縣市|外縣市|新北|桃園|臺中|台中|臺南|台南|高雄|基隆|新竹|苗栗|彰化|南投|雲林|嘉義|屏東|宜蘭|花蓮|臺東|台東|澎湖|金門|連江';
  final after = RegExp('(?:戶籍|設籍|戶口)[^，。；;\\n]{0,8}?($cities)')
      .firstMatch(proof)
      ?.group(1);
  final before = RegExp('($cities)(?:市|縣)?(?:的)?(?:戶籍|戶口)')
      .firstMatch(proof)
      ?.group(1);
  final city = after ?? before;
  if (city == null) return false;
  return value == '臺北市'
      ? RegExp(r'^(臺北|台北)$').hasMatch(city)
      : value == '其他縣市' && !RegExp(r'^(臺北|台北)$').hasMatch(city);
}

record_situation: Select ALL expressed needs/difficulties, at most 3 IDs from context.situations. housing=rent/housing, study=tuition/scholarships, living=living expenses/emergency aid, elder=elder care, family=childcare/birth, work=unemployment/training, health=medical/healthcare, disability=disability/aids, community=arts/community. Do NOT select negated needs. '房租和學費都付不起' requires both housing and study. '不要租屋，要學費補助' requires study only.
An explicitly requested kind of help takes precedence over the background cause. Do not replace a stated need with an unrelated topic inferred from the person's job, age or circumstances.
Parents are not automatically elderly-care needs. A request for a hearing aid/wheelchair because of disability selects disability only; elder requires an expressed need for elder/care services. Unemployment mentioned as background to a request for living assistance selects living only; work requires an expressed employment/training need. Multiple actual needs must still all be retained.
